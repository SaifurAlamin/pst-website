export function getProjectBySlug(slug) {
    return projects.find((project) => project.slug === slug);
}

export function getProjectCategories(locale) {
    const categories = projects.map((project) => ({
        value: project.category,
        label: project.categoryLabels[locale] || project.categoryLabels.en,
    }));

    const uniqueCategories = [
        ...new Map(
            categories.map((category) => [
                category.value,
                category,
            ])
        ).values(),
    ];

    return [
        {
            value: "all",
            label: locale === "ar" ? "جميع المشاريع" : "All Projects",
        },
        ...uniqueCategories,
    ];
}
